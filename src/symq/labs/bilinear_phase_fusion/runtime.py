"""Closed preparation and branch adapters for the native SymQ runtime.

Only a complete, phase-free producer with a fixed interface is accepted. The
garbage relation is reconstructed from its actual gates, never from a caller's
``prepared`` flag. This is not a general contextual replacement checker.
"""

from __future__ import annotations

import time

from symq.circuit import Circuit
from symq.phase import PhaseProgram

from .checker import Inconclusive, Rejected, canonical_digest, check_outcome, validate
from .compiler import branch
from .preparation import prove_preparation


def preparation_document(circuit: Circuit, program: dict, *, check=lambda: None) -> dict:
    """Snapshot a complete producer in order c, A, B words, clean garbage words.

    Its entire [0, len(gates)) interval is the source boundary. The checker
    proves that every live operand returns to its entry version. An arbitrary
    subinterval or wire map is deliberately unsupported.
    """
    validate(program, check=check)
    if type(circuit) is not Circuit:
        raise Rejected("an exact Circuit source is required")
    if type(circuit.gates) is not list or len(circuit.gates) > 200_000:
        raise Rejected("preparation source gate bound")
    snapshot = circuit.snapshot(check=check)
    m, bank = program["field"]["m"], program["bank"]
    if snapshot.width != program["width"] + m * bank:
        raise Rejected("preparation width does not match phase interface")
    return {
        "schema": "controlled-product-preparation-v1",
        "field": dict(program["field"]),
        "bank": bank,
        "width": snapshot.width,
        "gates": [[gate.name, list(gate.qubits)] for gate in snapshot.gates],
    }


def check_source_certificate(
    circuit: Circuit,
    program: dict,
    certificate: dict,
    *,
    seconds: float = 30.0,
    max_terms: int = 100_000,
) -> dict:
    """Replay one source-bound, prepared erasure branch on all quantum inputs.

    Both hashes and both obligations are rebuilt. The retained outcomes are the
    m*bank X measurements of the proved garbage words, LSB first. They are
    independent uniform branch labels. No extra HMR records are generated by
    the correction. Other instruments and enclosing applications are outside
    this theorem. Refusal and exhausted budgets never mean inequivalence.
    """
    from .checker import _deadline

    deadline = _deadline(seconds)
    keys = {"schema", "preparation_sha256", "program_sha256", "outcomes"}
    if type(certificate) is not dict or set(certificate) != keys:
        raise Rejected("source certificate schema")
    if certificate["schema"] != "bilinear-phase-erasure-branch-v1":
        raise Rejected("source certificate schema")

    def remaining():
        value = deadline - time.monotonic()
        if value <= 0:
            raise Inconclusive("source verification budget exhausted")
        return value

    source = preparation_document(circuit, program, check=remaining)
    if certificate["preparation_sha256"] != canonical_digest(source) or certificate[
        "program_sha256"
    ] != canonical_digest(program):
        raise Rejected("source binding")

    preparation = prove_preparation(source, seconds=remaining(), max_terms=max_terms)
    correction = check_outcome(program, certificate["outcomes"], seconds=remaining())
    remaining()
    return {
        "theorem": "prepared_bilinear_erasure_branch",
        "preparation_sha256": canonical_digest(source),
        "program_sha256": canonical_digest(program),
        "source_interval": [0, len(source["gates"])],
        "wire_order": "c, A[LSB first], B words[LSB first], zero garbage words",
        "live_operand_versions": "entry (proved restored by source and correction)",
        "retained_outcomes": list(certificate["outcomes"]),
        "outcome_bit_order": "word order, LSB first within each word",
        "additional_forgotten_outcomes": 0,
        "preparation": preparation,
        "correction": correction,
    }


def correction_for_outcome(program: dict, outcomes: list[int]) -> PhaseProgram:
    """Lower a checked concrete branch to sign-phase IR; introduces no HMR.

    This instantiates one classical branch, not an adaptive program or an
    exponential dispatch table. It does not establish a garbage relation.
    """
    check_outcome(program, outcomes)
    correction = PhaseProgram(data=program["width"])
    for name, *wires in branch(program, outcomes):
        correction.append(name, *wires)
    return correction
